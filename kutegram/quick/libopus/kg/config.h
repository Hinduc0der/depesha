/* Настройки сборки libopus для телефона. Обычно их пишет configure; здесь
 * они заданы руками, потому что configure под Symbian не запустить, а
 * выносить строковые -D в abld-сборку нельзя: кавычки до компилятора не
 * доходят (см. depesha.pro, там VERSION передаётся без кавычек).
 *
 * Файл подхватывается самим libopus: его исходники начинаются с
 * #ifdef HAVE_CONFIG_H #include "config.h".
 */
#ifndef KG_OPUS_CONFIG_H
#define KG_OPUS_CONFIG_H

/* ЦЕЛОЧИСЛЕННАЯ сборка. У ARM11 этого телефона плавающей точки в железе нет,
 * её считает библиотека -- на порядок медленнее. Opus для такого случая
 * написан целиком в целых числах, надо лишь попросить. */
#define FIXED_POINT 1

/* Временные массивы -- на стеке (массивы переменной длины из C99). Иначе
 * libopus требует alloca или свой «псевдостек»; первого под Symbian нет,
 * второй не потокобезопасен, а мы раскодируем в отдельном потоке. */
#define VAR_ARRAYS 1

/* Мы собираем саму библиотеку, а не пользуемся установленной. */
#define OPUS_BUILD 1

#define OPUS_VERSION "1.3.1"

/* Без плавающего интерфейса. Снимает с кодировщика анализ тональности
 * (analysis.c, mlp.c) -- он весь на float, а на этом телефоне плавающая
 * точка считается библиотекой. Из декодера убирает opus_decode_float,
 * которым мы не пользуемся. */
#define DISABLE_FLOAT_API 1

/* lrintf/lrint трогать не даём: это плавающая точка, а в целочисленной
 * сборке они нужны только путям, которых у нас нет. */

#endif /* KG_OPUS_CONFIG_H */
